#!/usr/bin/env node

/**
 * generate-image-urls.mjs
 *
 * Reads scripts/cloudinary-map.json (produced by upload-to-cloudinary.mjs)
 * and generates a static JS module at src/assets/data/cloudinaryUrls.js
 * that the frontend imports directly — no backend or runtime API calls.
 *
 * Usage:
 *   node scripts/generate-image-urls.mjs
 */

import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const PROJECT_ROOT = join(__dirname, '..');
const MAP_FILE = join(__dirname, 'cloudinary-map.json');
const OUTPUT_FILE = join(PROJECT_ROOT, 'src', 'assets', 'data', 'cloudinaryUrls.js');

async function main() {
  let map;
  try {
    const raw = await readFile(MAP_FILE, 'utf-8');
    map = JSON.parse(raw);
  } catch (err) {
    console.error('❌  Could not read scripts/cloudinary-map.json');
    console.error('   Run the upload script first: node scripts/upload-to-cloudinary.mjs');
    process.exit(1);
  }

  const entries = Object.entries(map);
  if (entries.length === 0) {
    console.error('❌  cloudinary-map.json is empty. Upload images first.');
    process.exit(1);
  }

  // Build the JS source
  const lines = [
    '// ┌──────────────────────────────────────────────────────────────────┐',
    '// │  AUTO-GENERATED by scripts/generate-image-urls.mjs             │',
    '// │  Do NOT edit manually — re-run the generator instead.          │',
    '// └──────────────────────────────────────────────────────────────────┘',
    '',
    '/**',
    ' * Maps original local public-folder paths to Cloudinary delivery URLs.',
    ' * Import `cloudinaryUrl` anywhere in the frontend to resolve an image.',
    ' */',
    'const CLOUDINARY_URLS = {',
  ];

  // Sort entries for deterministic output
  entries.sort(([a], [b]) => a.localeCompare(b));

  for (const [localPath, cloudUrl] of entries) {
    lines.push(`  '${localPath}': '${cloudUrl}',`);
  }

  lines.push('};');
  lines.push('');
  lines.push('export default CLOUDINARY_URLS;');
  lines.push('');
  lines.push('/**');
  lines.push(' * Resolve a local image path to its Cloudinary URL.');
  lines.push(' * Falls back to the original path if not found in the map.');
  lines.push(' *');
  lines.push(' * @param {string} localPath — e.g. "/departments/HR.JPG"');
  lines.push(' * @returns {string} Cloudinary URL or original path');
  lines.push(' */');
  lines.push('export function cloudinaryUrl(localPath) {');
  lines.push('  return CLOUDINARY_URLS[localPath] || localPath;');
  lines.push('}');
  lines.push('');

  const source = lines.join('\n');

  await writeFile(OUTPUT_FILE, source, 'utf-8');

  console.log(`✅  Generated ${OUTPUT_FILE}`);
  console.log(`   ${entries.length} image URLs mapped.`);
  console.log('');
  console.log('   The frontend will now use Cloudinary URLs for all images.');
  console.log('   Commit src/assets/data/cloudinaryUrls.js to your repo.');
}

main().catch((err) => {
  console.error('Fatal error:', err);
  process.exit(1);
});
